package com.lfn.common.app.web.rest.dto;

/**
 * DTO for GitHub Pull Request
 */
public class PullRequest {
    private String repoUrl;  // GitHub repository URL (e.g., https://github.com/owner/repo)
    private String branch;   // Branch name to pull from
    private String localPath; // Optional: Local path where to clone (if empty, creates temp directory)

    public PullRequest() {
    }

    public String getRepoUrl() {
        return repoUrl;
    }

    public void setRepoUrl(String repoUrl) {
        this.repoUrl = repoUrl;
    }

    public String getBranch() {
        return branch;
    }

    public void setBranch(String branch) {
        this.branch = branch;
    }

    public String getLocalPath() {
        return localPath;
    }

    public void setLocalPath(String localPath) {
        this.localPath = localPath;
    }
}

