package com.lfn.common.app.web.rest.dto;

import java.util.List;

/**
 * DTO for GitHub Pull Response
 */
public class PullResponse {
    private String localPath;  // Path where repository was cloned
    private String branch;     // Branch that was pulled
    private String commitHash; // Latest commit hash
    private List<FileContent> files; // List of files from the repository

    public PullResponse() {
    }

    public String getLocalPath() {
        return localPath;
    }

    public void setLocalPath(String localPath) {
        this.localPath = localPath;
    }

    public String getBranch() {
        return branch;
    }

    public void setBranch(String branch) {
        this.branch = branch;
    }

    public String getCommitHash() {
        return commitHash;
    }

    public void setCommitHash(String commitHash) {
        this.commitHash = commitHash;
    }

    public List<FileContent> getFiles() {
        return files;
    }

    public void setFiles(List<FileContent> files) {
        this.files = files;
    }
}

